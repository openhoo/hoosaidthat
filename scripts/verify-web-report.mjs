import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from '@playwright/test';

const reportPath = resolve(process.argv[2] ?? '');
if (!process.argv[2]) throw new Error('Usage: node scripts/verify-web-report.mjs path/to/report.html [screenshot-directory]');
const output = resolve(process.argv[3] ?? 'test-results/report-viewer');
await mkdir(output, { recursive: true });
const html = await readFile(reportPath, 'utf8');
const match = html.match(/<script id="report-data" type="application\/json">([\s\S]*?)<\/script>/);
assert.ok(match, 'Report contains its portable data');
const report = JSON.parse(match[1]);
assert.ok(report.snapshots.length >= 2, 'At least two real states captured');
const withAudio = report.snapshots.findIndex(snapshot => snapshot.observation.action === 'nextHeading' && snapshot.annotations.some(annotation => annotation.audio && annotation.bounds));
assert.ok(withAudio >= 0, 'Original audio and an element location in the same state');
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  const requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/^https?:/.test(request.url())) requests.push(request.url()); });
  await page.goto(pathToFileURL(reportPath).href);
  const buttons = page.locator('#steps button');
  assert.equal(await buttons.count(), report.snapshots.length);
  assert.equal(await page.locator('aside.inspector').count(), 0, 'Speech sidebar has been removed');
  const step = index => page.locator(`#steps button[data-step-index="${index}"]`);
  await step(withAudio).click();
  const annotationIndex = report.snapshots[withAudio].annotations.findIndex(annotation => annotation.audio && annotation.bounds);
  const pin = page.locator(`.annotation[data-utterance="${annotationIndex}"]`);
  assert.ok(await pin.isVisible());
  await pin.click();
  await page.waitForFunction(() => !document.getElementById('player').paused && document.getElementById('player').currentTime > 0);
  const duration = await page.locator('#player').evaluate(audio => audio.duration);
  const clip = report.snapshots[withAudio].annotations[annotationIndex].audio;
  assert.ok(Math.abs(duration - clip.sampleCount / clip.sampleRate) < .01, 'Browser decodes precisely the indexed clip');
  await page.screenshot({ path: `${output}/desktop.png`, fullPage: true, animations: 'disabled' });
  const different = report.snapshots.findIndex((snapshot, index) => index !== withAudio && snapshot.observation.action !== 'returnToPage' && snapshot.image);
  await step(different).click();
  assert.equal(await page.locator('#player').evaluate(audio => audio.paused), true, 'Changing state stops old audio');
  assert.equal(await page.locator('#stage img').getAttribute('src'), report.snapshots[different].image);
  await page.locator('#search').fill('impossible-search-8fd02');
  assert.equal(await page.locator('#steps button').count(), 0);
  await page.locator('#search').fill('');
  await step(withAudio).click();
  await page.locator('#toggle-annotations').click();
  assert.equal(await pin.isVisible(), false, 'Annotation visibility can be toggled');
  await page.locator('#toggle-annotations').click();
  assert.equal(await pin.isVisible(), true);
  await page.locator('#zoom').click();
  assert.equal(await page.locator('#stage').evaluate(stage => stage.clientWidth), report.snapshots[withAudio].width, 'Actual size mode preserves the screenshot resolution');
  await page.locator('#zoom').click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Mobile layout fits');
  await page.locator('#toggle-steps').click();
  await step(different).click();
  assert.equal(await page.locator('#toggle-steps').getAttribute('aria-expanded'), 'false', 'Mobile navigation closes after choosing a snapshot');
  await page.locator('#toggle-steps').click();
  await step(withAudio).click();
  await pin.focus();
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => !document.getElementById('player').paused);
  await page.waitForFunction(() => { const sidebar = document.getElementById('sidebar'); return new DOMMatrix(getComputedStyle(sidebar).transform).m41 <= -sidebar.offsetWidth + 1; });
  await page.screenshot({ path: `${output}/mobile.png`, fullPage: true, animations: 'disabled' });
  assert.deepEqual(errors, [], 'No viewer script errors');
  assert.deepEqual(requests, [], 'Portable report makes no network requests');
  console.log(JSON.stringify({ snapshots: report.snapshots.length, originalAudioClips: report.snapshots.flatMap(snapshot => snapshot.annotations).filter(annotation => annotation.audio).length, locatedAnnotations: report.snapshots.flatMap(snapshot => snapshot.annotations).filter(annotation => annotation.bounds).length, decodedClipDuration: duration, desktopAndMobile: 'passed', screenshots: output }, null, 2));
} finally {
  await browser.close();
}
